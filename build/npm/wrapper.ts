import { join } from "node:path";
import type { Logger } from "pino";
import { paths } from "../runtime/paths.ts";
import { fileSHA256, run } from "../runtime/runner.ts";

export async function writeWrapper(log: Logger) {
  const path = join(paths.dist.bin, "macbridge");
  await Bun.write(
    path,
    [
      "#!/usr/bin/env node",
      'import { spawnSync } from "node:child_process";',
      'import { existsSync } from "node:fs";',
      'import { dirname, join } from "node:path";',
      'import { fileURLToPath } from "node:url";',
      "",
      "const targets = {",
      '  "darwin-arm64": { suffix: "darwin-arm64" },',
      "};",
      'const installedApp = "/Applications/MacBridge.app";',
      'const lsregister = "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister";',
      "",
      'const key = process.platform + "-" + process.arch;',
      "const target = targets[key];",
      "if (target == null) {",
      '  process.stderr.write("macbridge currently supports Apple Silicon Macs only; got " + key + "\\n");',
      "  process.exit(1);",
      "}",
      "",
      "const args = process.argv.slice(2);",
      "const dir = dirname(fileURLToPath(import.meta.url));",
      'const packageJSONPath = join(dir, "..", "..", "package.json");',
      'const appBinary = join(installedApp, "Contents/MacOS/macbridge-runtime");',
      "",
      "function shellQuote(value) {",
      '  return "\'" + String(value).replaceAll("\'", "\'\\\\\'\'") + "\'";',
      "}",
      "",
      "function run(command, commandArgs, options = {}) {",
      '  return spawnSync(command, commandArgs, { stdio: options.stdio ?? "pipe", encoding: "utf8" });',
      "}",
      "",
      "function readVersion(app) {",
      '  const plist = join(app, "Contents/Info.plist");',
      '  const result = run("/usr/libexec/PlistBuddy", ["-c", "Print :CFBundleShortVersionString", plist]);',
      "  return result.status === 0 ? result.stdout.trim() : undefined;",
      "}",
      "",
      "function readPackageVersion() {",
      "  if (!existsSync(packageJSONPath)) return undefined;",
      '  const text = run("/bin/cat", [packageJSONPath]);',
      "  if (text.status !== 0) return undefined;",
      "  try {",
      "    return JSON.parse(text.stdout).version;",
      "  } catch {",
      "    return undefined;",
      "  }",
      "}",
      "",
      "const expectedVersion = readPackageVersion();",
      "const installerPkg =",
      "  expectedVersion == null",
      "    ? undefined",
      '    : join(dir, "..", "pkg", "macbridge-" + expectedVersion + "-" + target.suffix + ".pkg");',
      "",
      "function appNeedsInstall() {",
      "  const installedVersion = readVersion(installedApp);",
      "  if (expectedVersion == null) return installedVersion == null;",
      "  return installedVersion !== expectedVersion;",
      "}",
      "",
      "function installApp() {",
      "  if (installerPkg == null || !existsSync(installerPkg)) {",
      '    process.stderr.write("Missing installer payload in package for version " + String(expectedVersion) + "\\n");',
      "    process.exit(1);",
      "  }",
      '  const direct = run("/usr/sbin/installer", ["-pkg", installerPkg, "-target", "/"], { stdio: "inherit" });',
      "  if (direct.status === 0) return;",
      '  const script = "/usr/sbin/installer -pkg " + shellQuote(installerPkg) + " -target /";',
      "  const elevated = run(",
      '    "/usr/bin/osascript",',
      '    ["-e", "do shell script " + JSON.stringify(script) + " with administrator privileges"],',
      '    { stdio: "inherit" },',
      "  );",
      "  if (elevated.status !== 0) {",
      '    process.stderr.write("MacBridge installer failed.\\n");',
      "    process.exit(elevated.status ?? 1);",
      "  }",
      "}",
      "",
      "function ensureInstalledApp() {",
      "  if (appNeedsInstall()) installApp();",
      "  if (!existsSync(installedApp)) {",
      '    process.stderr.write("MacBridge.app is not installed at /Applications after installer run.\\n");',
      "    process.exit(1);",
      "  }",
      '  run(lsregister, ["-f", installedApp]);',
      "}",
      "",
      "ensureInstalledApp();",
      "process.env.BIN ??= appBinary;",
      "if (args.length === 0) {",
      '  const opened = run("/usr/bin/open", [installedApp], { stdio: "inherit" });',
      "  process.exit(opened.status ?? 1);",
      "}",
      "if (process.versions.bun != null) {",
      '  const { runCLI } = await import("../index.js");',
      "  process.exit(await runCLI(args));",
      "}",
      "const self = fileURLToPath(import.meta.url);",
      'const routed = spawnSync("bun", [self, ...args], { stdio: "inherit", env: { ...process.env, BIN: process.env.BIN ?? appBinary } });',
      "if (routed.error == null) process.exit(routed.status ?? 1);",
      'if (routed.error.code !== "ENOENT") throw routed.error;',
      'const result = spawnSync(appBinary, args, { stdio: "inherit" });',
      "if (result.error != null) throw result.error;",
      "process.exit(result.status ?? 1);",
      "",
    ].join("\n"),
  );
  await run(log, ["chmod", "755", path]);
  return {
    path,
    kind: "npm-bin-wrapper",
    sha256: await fileSHA256(path),
    size: Bun.file(path).size,
  };
}
