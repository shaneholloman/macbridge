import { createLogger } from "../src/core/log.ts";

type Status = "Draft" | "In Progress" | "Accepted" | "Implemented" | "Rejected" | "Superseded";

type RFC = {
  id: string;
  name: string;
  status: Status;
  file: string;
  desiredFile: string;
  relativeFile: string;
  desiredRelativeFile: string;
};

const logger = createLogger("rfc");
const root = "docs/development/rfcs";
const implemented = `${root}/implemented`;
const indexPath = `${root}/index.md`;
const readmePath = "README.md";
const allowedStatuses = new Set<Status>([
  "Draft",
  "In Progress",
  "Accepted",
  "Implemented",
  "Rejected",
  "Superseded",
]);

function usage(): string {
  return ["usage:", "  bun build/rfc.ts check", "  bun build/rfc.ts sync"].join("\n");
}

function fail(message: string): never {
  logger.error({ message }, "RFC workflow failed");
  process.exit(1);
}

function slug(value: string): string {
  return value
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, "-")
    .replaceAll(/^-|-$/g, "");
}

function parseFrontmatter(path: string, text: string): Record<string, string> {
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  if (match == null) fail(`${path} is missing YAML frontmatter`);
  const body = match[1];
  if (body == null) fail(`${path} has invalid YAML frontmatter`);

  const frontmatter: Record<string, string> = {};
  for (const line of body.split("\n")) {
    const field = line.match(/^([a-z_]+):\s*(.*)$/);
    if (field == null) continue;
    const key = field[1];
    const value = field[2];
    if (key == null || value == null) continue;
    frontmatter[key] = value.trim().replace(/^["']|["']$/g, "");
  }
  return frontmatter;
}

function relative(path: string): string {
  return path.startsWith(`${root}/`) ? path.slice(root.length + 1) : path;
}

async function discoverRFCs(): Promise<RFC[]> {
  const proc = Bun.spawnSync({
    cmd: ["find", root, "-type", "f", "-name", "rfc-[0-9][0-9][0-9][0-9]-*.md"],
    stdin: "ignore",
    stdout: "pipe",
    stderr: "pipe",
  });
  if (proc.exitCode !== 0) {
    fail(proc.stderr.toString().trimEnd() || "failed to discover RFC files");
  }

  const files = proc.stdout
    .toString()
    .trim()
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .sort();

  const rfcs: RFC[] = [];
  for (const file of files) {
    const text = await Bun.file(file).text();
    const frontmatter = parseFrontmatter(file, text);
    const id = frontmatter.id;
    const name = frontmatter.name;
    const status = frontmatter.status as Status | undefined;
    if (id == null || !/^RFC-\d{4}$/.test(id)) fail(`${file} has invalid id`);
    if (name == null || name === "") fail(`${file} has invalid name`);
    if (status == null || !allowedStatuses.has(status)) fail(`${file} has invalid status`);

    const basename = `rfc-${id.slice(4).toLowerCase()}-${slug(name)}.md`;
    const desiredFile =
      status === "Implemented" ? `${implemented}/${basename}` : `${root}/${basename}`;
    rfcs.push({
      id,
      name,
      status,
      file,
      desiredFile,
      relativeFile: relative(file),
      desiredRelativeFile: relative(desiredFile),
    });
  }

  const ids = new Set<string>();
  for (const rfc of rfcs) {
    if (ids.has(rfc.id)) fail(`duplicate RFC id: ${rfc.id}`);
    ids.add(rfc.id);
  }

  return rfcs.sort((a, b) => a.id.localeCompare(b.id));
}

function renderIndex(rfcs: RFC[]): string {
  const rows = rfcs.map((rfc) => [rfc.id, rfc.status, `\`${rfc.desiredRelativeFile}\``, rfc.name]);
  const headers = ["ID", "Status", "File", "Title"];
  const widths = headers.map((header, index) =>
    Math.max(header.length, ...rows.map((row) => row[index]?.length ?? 0)),
  );
  const render = (row: string[]) =>
    `| ${row.map((cell, index) => cell.padEnd(widths[index] ?? 0)).join(" | ")} |`;
  const separator = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;

  return [
    "# RFC Index",
    "",
    "Generated from RFC frontmatter. Do not edit this file manually.",
    "",
    "Implemented RFC files live under `docs/development/rfcs/implemented/`. All",
    "other RFCs remain in `docs/development/rfcs/`.",
    "",
    render(headers),
    separator,
    ...rows.map(render),
    "",
  ].join("\n");
}

function renderReadmeSection(rfcs: RFC[]): string {
  const lines = [
    "## Architecture RFCs",
    "",
    "Architecture and contract decisions live under `docs/development/rfcs`.",
    "",
    "Current RFC index:",
    "",
    "- [RFC Index](docs/development/rfcs/index.md)",
  ];

  const active = rfcs.filter((rfc) => rfc.status !== "Implemented");
  if (active.length > 0) {
    lines.push("", "Active RFCs:", "");
    for (const rfc of active) {
      lines.push(`- [${rfc.id}: ${rfc.name}](docs/development/rfcs/${rfc.desiredRelativeFile})`);
    }
  }

  return lines.join("\n");
}

function replaceReadmeSection(readme: string, section: string): string {
  const start = readme.indexOf("## Architecture RFCs");
  if (start === -1) fail("README.md is missing ## Architecture RFCs section");
  const next = readme.indexOf("\n## ", start + 1);
  if (next === -1) return `${readme.slice(0, start)}${section}\n`;
  return `${readme.slice(0, start)}${section}\n\n${readme.slice(next + 1)}`;
}

async function writeIfChanged(path: string, content: string): Promise<boolean> {
  const file = Bun.file(path);
  const previous = (await file.exists()) ? await file.text() : "";
  if (previous === content) return false;
  await Bun.write(path, content);
  return true;
}

async function sync(): Promise<string[]> {
  await Bun.$`mkdir -p ${implemented}`.quiet();
  let rfcs = await discoverRFCs();
  const changed: string[] = [];

  for (const rfc of rfcs) {
    if (rfc.file !== rfc.desiredFile) {
      await Bun.$`mkdir -p ${rfc.desiredFile.split("/").slice(0, -1).join("/")}`.quiet();
      await Bun.$`mv ${rfc.file} ${rfc.desiredFile}`.quiet();
      changed.push(`moved ${rfc.relativeFile} -> ${rfc.desiredRelativeFile}`);
    }
  }

  rfcs = await discoverRFCs();
  if (await writeIfChanged(indexPath, renderIndex(rfcs))) {
    changed.push(`updated ${indexPath}`);
  }

  const readme = await Bun.file(readmePath).text();
  if (await writeIfChanged(readmePath, replaceReadmeSection(readme, renderReadmeSection(rfcs)))) {
    changed.push(`updated ${readmePath}`);
  }

  return changed;
}

async function check(): Promise<void> {
  const before = new Map<string, string>();
  for (const path of [indexPath, readmePath]) {
    before.set(path, await Bun.file(path).text());
  }

  const changed = await sync();
  const drift: string[] = [];
  for (const [path, content] of before) {
    if ((await Bun.file(path).text()) !== content) drift.push(path);
  }
  if (changed.some((item) => item.startsWith("moved "))) {
    drift.push(...changed.filter((item) => item.startsWith("moved ")));
  }

  if (drift.length > 0) {
    fail(`RFC files were out of sync; updated ${drift.join(", ")}. Review and rerun.`);
  }

  logger.info("RFC workflow check passed");
}

const command = process.argv[2];
if (command === "sync") {
  const changed = await sync();
  if (changed.length === 0) {
    logger.info("RFC workflow already in sync");
  } else {
    logger.info({ changed }, "RFC workflow synced");
  }
} else if (command === "check") {
  await check();
} else {
  fail(usage());
}
